#boolean se refere á True e False, onde True é 1 e False é 0
#com um booleano podemos fazer comparações entre valores
#maior que = >
maior = 5 > 2
print("Maior que: ", maior)
#menor que = <
menor = 2 < 5
print("Menor que: ", menor)
#igual a = ==
igual = 3 == 3
print("Igual a: ", igual)
#diferente de = !=
diferente = 4 != 2
print("Diferente de: ", diferente)
#maior ou igual a = >=
maior_igual = 5 >= 5
print("Maior ou igual a: ", maior_igual)
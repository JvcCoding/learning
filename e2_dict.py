#o tipo de armazenamento dicionario é representado por chaves {}, e é o tipo mais flexivel de armazenamento
#dicionarios armazenam dados em pares de chave: valor, onde a chave é unica
meu_dicionario = {
    "nome": "João",
    "idade": 25,
    "cidade": "São Paulo"
}
print("Dicionário: ", meu_dicionario)
#para acessar um valor dentro do dicionario, usamos a chave correspondente
print("Nome: ", meu_dicionario["nome"])
print("Idade: ", meu_dicionario["idade"])
print("Cidade: ", meu_dicionario["cidade"])
#podemos adicionar novos pares chave: valor ao dicionario

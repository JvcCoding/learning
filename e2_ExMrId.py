#aqui estudarei sobre exponentes, remainder e integer division
#exponentes são representados por dois asteriscos (**), onde o numero que vem apos é o numero que estará sendo elevado
exponente = 2 ** 3
print("Exponente: ", exponente)

#remainder é representado pelo simbolo de porcentagem (%), onde o resultado é o resto de uma divisão
remainder = 10 % 3
print("Remainder: ", remainder)

#integer division é representada por duas barras (//), onde o resultado é a parte inteira da divisão
integer_division = 10 // 3
print("Integer Division: ", integer_division)
